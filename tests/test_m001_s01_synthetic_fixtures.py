"""M001-S01: deterministic synthetic replacements for the excluded raw fixtures.

``tests/data/full_output/full_output.csv`` and ``tests/data/biomet/biomet.csv``
are generated by ``synthetic_eddy.py`` (no real observations). These tests
pin their bytes to the generator and require that the native hesseflux
default produces a real partition on them (C2: at least 48 paired finite
GPP/Reco rows and no partition-failure warning), so shape-only assertions in
the legacy tests cannot pass on all-NaN partition output.
"""
from __future__ import annotations

import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import synthetic_eddy
from miaproc.eddy import HessefluxConfig, load_stage1, postproc

DATA = Path(__file__).parent / "data"
MIN_PAIRED_FINITE = 48
PARTITION_FAILURE_MARKERS = ("partitioning failed", "without gpp", "gap-filled nee")


def _stage1() -> pd.DataFrame:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return load_stage1(
            path_full_output=DATA / "full_output",
            path_biomet=DATA / "biomet",
            tz_in="UTC",
            tz_out="UTC",
            skip_full_output=0,
            skip_biomet=0,
            drop_rain_rows=True,
        )


def test_committed_fixtures_match_deterministic_generator():
    texts = synthetic_eddy.render_csv_texts(
        days=synthetic_eddy.TEST_FIXTURE_DAYS, seed=synthetic_eddy.TEST_FIXTURE_SEED
    )
    assert sorted(texts) == ["biomet/biomet.csv", "full_output/full_output.csv"]
    for rel, text in texts.items():
        committed = (DATA / rel).read_bytes().replace(b"\r\n", b"\n")
        assert committed == text.encode("utf-8"), rel


def test_generator_is_seed_deterministic_and_seed_sensitive():
    a = synthetic_eddy.render_csv_texts(days=3, seed=1)
    b = synthetic_eddy.render_csv_texts(days=3, seed=1)
    c = synthetic_eddy.render_csv_texts(days=3, seed=2)
    assert a == b
    assert a["full_output/full_output.csv"] != c["full_output/full_output.csv"]


def test_fixture_has_legacy_eddypro_shape():
    flux = pd.read_csv(DATA / "full_output" / "full_output.csv", dtype=str)
    biomet = pd.read_csv(DATA / "biomet" / "biomet.csv", dtype=str)
    assert list(flux.columns) == list(synthetic_eddy.FLUX_COLUMNS)
    assert list(biomet.columns) == list(synthetic_eddy.BIOMET_COLUMNS)
    # Second header row is the EddyPro unit row dropped by stage 1.
    assert flux.loc[0, "time"] == "[HH:MM]"
    assert biomet.loc[0, "time"] == "[HH:MM]"
    # Missing values use the EddyPro sentinel; some timestamps are absent.
    assert (flux["co2_flux"] == "-9999").any()
    assert len(flux) - 1 < synthetic_eddy.TEST_FIXTURE_DAYS * 48
    assert len(biomet) - 1 == synthetic_eddy.TEST_FIXTURE_DAYS * 48


def test_stage1_exercises_qc_rain_and_regularization():
    df = _stage1()
    n_expected = synthetic_eddy.TEST_FIXTURE_DAYS * 48
    assert len(df) == n_expected
    assert df["DateTime"].is_monotonic_increasing
    assert (df["DateTime"].diff().dropna() == pd.Timedelta(minutes=30)).all()
    # Inserted grid rows (dropped timestamps, rain rows) carry no measurements.
    assert df["date"].isna().sum() > 0
    assert df["NEE"].notna().sum() > 0.6 * n_expected
    # Kelvin -> Celsius conversion applied to plausible coastal temperatures.
    assert df["Tair"].dropna().between(5, 45).all()


@pytest.mark.parametrize(
    "config",
    [
        pytest.param(HessefluxConfig(), id="default-fixed-lasslop-native"),
        pytest.param(HessefluxConfig(partition_method="reichstein"), id="reichstein"),
        pytest.param(
            HessefluxConfig(ustar_mode="dynamic", ustar_min_night_samples=200),
            id="dynamic-lasslop-native",
        ),
    ],
)
def test_hesseflux_partition_is_real_on_fixture(config):
    df = _stage1()
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        out = postproc(df, engine="hesseflux", hesseflux_config=config)
    failures = [
        str(w.message) for w in caught
        if any(k in str(w.message).lower() for k in PARTITION_FAILURE_MARKERS)
    ]
    assert failures == []
    gpp = out["GPP"].to_numpy(dtype=float)
    reco = out["Reco"].to_numpy(dtype=float)
    paired = np.isfinite(gpp) & np.isfinite(reco)
    assert int(paired.sum()) >= MIN_PAIRED_FINITE
    # Physically sensible partition of a net-uptake synthetic ecosystem.
    assert np.nanmean(reco[paired]) > 0
    assert np.nanmean(gpp[paired]) > 0
